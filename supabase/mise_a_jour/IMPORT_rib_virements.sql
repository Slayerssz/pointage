-- ▶ Qui reste sans R.I.B. alors qu'il est payé par virement
select c.name as societe, e.matricule, e.nom_prenom, e.cnss
  from public.employees e
  join public.companies c on c.id = e.company_id
 where e.actif and e.archive_le is null
   and lower(coalesce(e.mode_reglement,'')) like 'vir%'
   and (e.rib is null or trim(e.rib) = '')
 order by c.name, e.nom_prenom;
